-- Run this in Supabase Dashboard -> SQL Editor.
-- (Skip the CREATE TABLE if you already have your own products table;
--  the app only needs: id, name, price, stock, category, image_url.)

create table if not exists public.products (
  id          bigint generated by default as identity primary key,
  name        text not null,
  description text,
  price       numeric(10,2) not null check (price >= 0),
  stock       integer not null default 0 check (stock >= 0),
  category    text,
  image_url   text,
  created_at  timestamptz not null default now()
);

-- Speeds up the price range filter + ordering used by the app.
create index if not exists products_price_idx on public.products (price);

-- Row Level Security: with RLS on and no policies, the API returns nothing.
alter table public.products enable row level security;

-- Open policies for a class activity (anyone with the anon key can use them).
-- Tighten these (e.g. auth.uid() checks) for a real app.
drop policy if exists "products_select" on public.products;
drop policy if exists "products_insert" on public.products;
drop policy if exists "products_update" on public.products;
drop policy if exists "products_delete" on public.products;

create policy "products_select" on public.products for select using (true);
create policy "products_insert" on public.products for insert with check (true);
create policy "products_update" on public.products for update using (true) with check (true);
create policy "products_delete" on public.products for delete using (true);

