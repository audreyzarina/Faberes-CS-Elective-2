-- is_admin(): true when the signed-in user's role is 'admin'.
-- SECURITY DEFINER so it can read profiles/roles without triggering the
-- profiles policies again (which would recurse).
create or replace function public.is_admin()
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  return exists (
    select 1
    from public.profiles p
    join public.roles r on r.id = p.role_id
    where p.id = auth.uid()
      and r.role = 'admin'
  );
end;
$$;

revoke all on function public.is_admin() from public, anon;
grant execute on function public.is_admin() to authenticated;

-- handle_new_user(): creates the profile row for every new auth user
-- (email/password AND Google). The role is ALWAYS 'customer'; nothing the
-- client sends can change that.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email, firstname, lastname, role_id)
  values (
    new.id,
    new.email,
    coalesce(
      new.raw_user_meta_data ->> 'firstname',
      new.raw_user_meta_data ->> 'given_name',
      nullif(split_part(coalesce(new.raw_user_meta_data ->> 'full_name',
                                 new.raw_user_meta_data ->> 'name', ''), ' ', 1), '')
    ),
    coalesce(
      new.raw_user_meta_data ->> 'lastname',
      new.raw_user_meta_data ->> 'family_name'
    ),
    (select id from public.roles where role = 'customer')
  );
  return new;
end;
$$;

-- Trigger: run handle_new_user after every sign-up.
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- place_order(): the ONLY way to create an order.
--   * runs as one transaction: any failure saves nothing
--   * names, prices and stock come from the database, never from the app
--   * locks product rows, checks stock, reduces stock
--   * stores a name + unit price snapshot on every order item
--   * saves the order with status 'done'
create or replace function public.place_order(p_items jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid      uuid := auth.uid();
  v_order_id bigint;
  v_total    numeric := 0;
  v_item     record;
  v_product  record;
  v_price    numeric;
begin
  if v_uid is null then
    raise exception 'You must be signed in to place an order.' using errcode = '42501';
  end if;

  if public.is_admin() then
    raise exception 'Admins cannot place orders.' using errcode = '42501';
  end if;

  if p_items is null
     or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) = 0 then
    raise exception 'Your cart is empty.';
  end if;

  insert into public.orders (user_id, status, total)
  values (v_uid, 'done', 0)
  returning id into v_order_id;

  -- Merge duplicate product lines and lock in a fixed order (avoids deadlocks).
  for v_item in
    select (e ->> 'product_id')::bigint as product_id,
           sum((e ->> 'quantity')::int) as quantity
    from jsonb_array_elements(p_items) as e
    group by 1
    order by 1
  loop
    if v_item.quantity is null or v_item.quantity <= 0 then
      raise exception 'Invalid quantity in your cart.';
    end if;

    select id, name, price, stock
    into v_product
    from public.products
    where id = v_item.product_id
    for update;

    if not found then
      raise exception 'A product in your cart is no longer available.';
    end if;

    if v_product.stock < v_item.quantity then
      raise exception 'Not enough stock for % (available: %).', v_product.name, v_product.stock;
    end if;

    v_price := round(coalesce(v_product.price, 0)::numeric, 2);

    update public.products
    set stock = stock - v_item.quantity
    where id = v_product.id;

    insert into public.order_items (order_id, product_id, product_name, unit_price, quantity)
    values (v_order_id, v_product.id, v_product.name, v_price, v_item.quantity);

    v_total := v_total + v_price * v_item.quantity;
  end loop;

  update public.orders set total = v_total where id = v_order_id;

  return jsonb_build_object('order_id', v_order_id, 'total', v_total);
end;
$$;

revoke all on function public.place_order(jsonb) from public, anon;
grant execute on function public.place_order(jsonb) to authenticated;

