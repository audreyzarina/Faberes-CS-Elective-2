-- ---------------------------------------------------------------------
-- 2. Schema adjustments
--    * order_items keeps a snapshot of the product name (price snapshot is unit_price)
--    * product_id may become NULL if a product is deleted (history stays intact)
--    * deleting an order removes its items
-- ---------------------------------------------------------------------
alter table public.order_items add column if not exists product_name text;

update public.order_items oi
set product_name = p.name
from public.products p
where oi.product_id = p.id and oi.product_name is null;

update public.order_items set product_name = 'Removed product' where product_name is null;
alter table public.order_items alter column product_name set not null;

alter table public.order_items alter column product_id drop not null;

do $$
declare
  col text;
  c record;
begin
  foreach col in array array['product_id', 'order_id'] loop
    for c in
      select con.conname
      from pg_constraint con
      join pg_attribute a
        on a.attrelid = con.conrelid and a.attnum = any (con.conkey)
      where con.conrelid = 'public.order_items'::regclass
        and con.contype = 'f'
        and a.attname = col
    loop
      execute format('alter table public.order_items drop constraint %I', c.conname);
    end loop;
  end loop;
end $$;

