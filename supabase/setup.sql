-- Start clean so the policies below are exactly the ones in the permission table.
do $$
declare r record;
begin
  for r in
    select schemaname, tablename, policyname
    from pg_policies
    where schemaname = 'public'
      and tablename in ('profiles','roles','categories','products','orders','order_items')
  loop
    execute format('drop policy %I on %I.%I', r.policyname, r.schemaname, r.tablename);
  end loop;
end $$;

-- profiles: customer reads/updates own row only (never the role); admin reads all
create policy "profiles read own" on public.profiles
  for select to authenticated using (id = auth.uid());
create policy "profiles read all (admin)" on public.profiles
  for select to authenticated using (public.is_admin());
create policy "profiles update own" on public.profiles
  for update to authenticated
  using (id = auth.uid()) with check (id = auth.uid());

-- Column-level privileges: a user can only ever change their own names,
-- so role_id (and id/email) can never be edited from the app.
revoke insert, update, delete on public.profiles from anon, authenticated;
grant update (firstname, lastname) on public.profiles to authenticated;

-- roles: read only
create policy "roles read" on public.roles
  for select to authenticated using (true);

-- categories: everyone signed in reads; admin adds/edits/deletes
create policy "categories read" on public.categories
  for select to authenticated using (true);
create policy "categories insert (admin)" on public.categories
  for insert to authenticated with check (public.is_admin());
create policy "categories update (admin)" on public.categories
  for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "categories delete (admin)" on public.categories
  for delete to authenticated using (public.is_admin());

-- products: everyone signed in reads; admin adds/edits/deletes
create policy "products read" on public.products
  for select to authenticated using (true);
create policy "create product" on public.products
  for insert to authenticated with check (public.is_admin());
create policy "update product" on public.products
  for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "delete product" on public.products
  for delete to authenticated using (public.is_admin());

-- orders: customer reads own; admin reads all and updates status.
-- There is deliberately NO insert policy: orders are created only by place_order().
create policy "orders read own" on public.orders
  for select to authenticated using (user_id = auth.uid());
create policy "orders read all (admin)" on public.orders
  for select to authenticated using (public.is_admin());
create policy "orders update status (admin)" on public.orders
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

revoke insert, update, delete on public.orders from anon, authenticated;
grant update (status) on public.orders to authenticated;

-- order_items: customer reads items of own orders; admin reads all.
-- No insert/update/delete policies: only place_order() writes them.
create policy "order_items read own" on public.order_items
  for select to authenticated
  using (exists (
    select 1 from public.orders o
    where o.id = order_items.order_id and o.user_id = auth.uid()
  ));
create policy "order_items read all (admin)" on public.order_items
  for select to authenticated using (public.is_admin());

revoke insert, update, delete on public.order_items from anon, authenticated;

-- Signed-out users get nothing: no policy targets the anon role, and
-- table privileges are removed for it as well.
revoke all on public.profiles, public.roles, public.categories, public.products,
              public.orders, public.order_items from anon;

